local test = require "integration_test"
local capabilities = require "st.capabilities"
local clusters = require "st.zigbee.zcl.clusters"
local helpers = require "test.zemismart_feedback_test_utils"
local device = helpers.create()
local battery_device = helpers.create("window-treatment-battery.yml")
local shade = capabilities.windowShade.windowShade
helpers.set_test_init(device)

local function assert_position(level, state)
  assert(device:get_latest_state("main", "windowShadeLevel", "shadeLevel") == level)
  assert(device:get_latest_state("main", "windowShade", "windowShade") == state)
end

local function expect_position(level, state)
  helpers.expect_event(capabilities.windowShadeLevel.shadeLevel(level))
  helpers.expect_event(state)
end

local function unknown()
  helpers.report(0xFF)
  helpers.expect_event(shade.unknown())
  test.wait_for_events()
end

local function suspect_zero()
  helpers.report(0)
  helpers.expect_read()
  test.wait_for_events()
end

test.register_coroutine_test("Startup initializes metadata without a read or Unknown", function()
  test.wait_for_events()
  assert(device:get_latest_state("main", "windowShade", "windowShade") == nil)
  assert(device:get_latest_state("main", "windowShadeLevel", "shadeLevel") == nil)
  helpers.advance(35)
end)

test.register_coroutine_test("Driver restart preserves a known static position without Zigbee traffic", function()
  helpers.seed(43)
  test.socket.device_lifecycle:__queue_receive({ device.id, "init" })
  test.wait_for_events()
  helpers.advance(35)
  assert_position(43, "partially open")
end)

for _, level in ipairs({ 0, 43, 100 }) do
  test.register_coroutine_test("First static read publishes position " .. level .. " without invented motion", function()
    helpers.seed(level)
  end)
end

for _, action in ipairs({
  { "windowShade", "open", "UpOrOpen" },
  { "windowShade", "close", "DownOrClose" },
  { "windowShade", "pause", "Stop" },
  { "windowShadeLevel", "setShadeLevel", "GoToLiftPercentage", 75, { 75 } },
  { "windowShadePreset", "presetPosition", "GoToLiftPercentage", 50 },
}) do
  test.register_coroutine_test("Unknown never blocks " .. action[2] .. " and same-value feedback restores state", function()
    helpers.seed(43)
    unknown()
    helpers.command(action[1], action[2], action[5])
    helpers.expect_motion(action[3], action[4])
    test.wait_for_events()
    assert_position(43, "unknown")
    helpers.report(43)
    helpers.expect_static(43)
    test.wait_for_events()
    assert_position(43, "partially open")
  end)
end

test.register_coroutine_test("Unknown never blocks a relative step from the last real position", function()
  helpers.seed(43)
  unknown()
  helpers.step(10, 53)
  assert_position(43, "unknown")
  helpers.response(43)
  helpers.expect_static(43)
end, { min_api_version = 15 })

