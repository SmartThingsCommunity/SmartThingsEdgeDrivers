test.register_coroutine_test("Failed anomaly read keeps a bounded real report and leaves commands available", function()
  helpers.seed(43)
  local position = clusters.WindowCovering.attributes.CurrentPositionLiftPercentage
  local handler = (require "zemismart.position_recovery").position_handler
  local callbacks, restore = helpers.capture_callbacks()
  local original_send = device.send_to_component
  device.send_to_component = function() error("simulated read send failure") end
  local ok, err = pcall(handler, {}, device, { value = 0 }, position:build_test_attr_report(device, 0))
  device.send_to_component = original_send
  restore()
  assert(not ok and string.find(err, "simulated read send failure", 1, true))
  helpers.expect_static(0)
  callbacks[1].callback()
  test.wait_for_events()
  helpers.command("windowShade", "open")
  helpers.expect_motion("UpOrOpen")
  test.wait_for_events()
  assert_position(0, "closed")
end)

